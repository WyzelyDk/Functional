namespace Wyzely.Functional.CodeGeneration;

/// <summary>Writes the library method of one operation for one combination of receiver and delegate, with complete XML documentation.</summary>
internal sealed class LibraryEmitter(GeneratorProfile profile)
{
    internal string Emit(OperationSpec operation, Variant variant, bool stubs)
    {
        var writer = new CodeWriter();
        writer.Line("// <auto-generated>");
        writer.Line($"//     This file was generated by {profile.ToolNamespace}. Do not edit it by hand:");
        writer.Line($"//     change the generator and run `dotnet run --project {profile.ToolProject}`.");
        writer.Line("// </auto-generated>");
        writer.Line("#nullable enable");
        writer.Line();
        writer.Line("using System.Runtime.CompilerServices;");
        writer.Line();
        writer.Line("namespace Wyzely.Functional;");
        writer.Line();
        writer.Line("/// <content>");
        var receiverLine = $"/// The <c>{operation.Name}</c> operation for {operation.ReceiverDescription}, with a {variant.Receiver.Label()} receiver";

        if (operation.Delegates.Length == 0)
        {
            writer.Line(receiverLine + ".");
        }
        else
        {
            writer.Line(receiverLine);
            writer.Line(operation.HasIndependentDelegate
                ? $"/// and a {variant.Delegate.Label()} delegate and a {variant.Second.Label()} delegate of the second kind."
                : $"/// and a {variant.Delegate.Label()} delegate.");
        }

        writer.Line("/// </content>");
        writer.Line($"public static partial class {profile.ExtensionsClass}");
        writer.Open();
        EmitVariant(writer, operation, variant, stubs);
        writer.Close();

        return writer.ToString();
    }

    private static List<string> GuardedNames(OperationSpec operation, Variant variant, string receiverName)
    {
        var names = new List<string>();

        if (variant.Receiver == Wrapper.Task)
        {
            names.Add(receiverName);
        }

        names.AddRange(operation.LeadingParameters.Where(leading => leading.Validated).Select(leading => leading.Name));
        names.AddRange(operation.Delegates.Select(@delegate => @delegate.Name));
        names.AddRange(operation.ExtraParameters.Where(extra => extra.Validated).Select(extra => extra.Name));

        return names;
    }

    // The synchronous variant for an asynchronous delegate returns the kind of the delegate; the caller wants the kind of the receiver.
    private static string ConvertInner(OperationSpec operation, Variant variant)
    {
        if (variant.Receiver == new Variant(Wrapper.None, variant.Delegate, variant.Second).Result)
        {
            return "inner";
        }

        if (variant.Receiver == Wrapper.Task)
        {
            return "inner.AsTask()";
        }

        return operation.ReturnsVoid ? "new ValueTask(inner)" : $"new ValueTask<{operation.ReturnType}>(inner)";
    }

    private static List<string> BuildParameters(OperationSpec operation, Variant variant, string receiverType, string receiverName)
    {
        var parameters = new List<string> { $"{receiverType} {receiverName}" };

        foreach (var leading in operation.LeadingParameters)
        {
            parameters.Add($"{leading.Type} {leading.Name}");
        }

        foreach (var @delegate in operation.Delegates)
        {
            parameters.Add($"{@delegate.TypeFor(variant.WrapperOf(@delegate))} {@delegate.Name}");
        }

        foreach (var extra in operation.ExtraParameters)
        {
            parameters.Add($"{extra.Type} {extra.Name}");
        }

        return parameters;
    }

    private static string ReturnSentence(OperationSpec operation, Variant variant)
    {
        if (operation.ReturnsVoid || variant.Result == Wrapper.None)
        {
            return string.Empty;
        }

        return variant.Result == Wrapper.Task
            ? " The value is returned in a <see cref=\"Task{TResult}\"/>."
            : " The value is returned in a <see cref=\"ValueTask{TResult}\"/>.";
    }

    private static string[] StubBody(OperationSpec operation, Variant variant)
    {
        if (operation.ReturnsVoid)
        {
            return variant.Result switch
            {
                Wrapper.None => [],
                Wrapper.Task => ["return Task.CompletedTask;"],
                _ => ["return default;"],
            };
        }

        return variant.Result switch
        {
            Wrapper.None => ["return default!;"],
            Wrapper.Task => [$"return Task.FromResult(default({operation.ReturnType})!);"],
            _ => [$"return new ValueTask<{operation.ReturnType}>(default({operation.ReturnType})!);"],
        };
    }

    private void EmitVariant(CodeWriter writer, OperationSpec operation, Variant variant, bool stubs)
    {
        var receiverName = profile.ReceiverParameter;
        var receiverType = variant.Receiver.Wrap(operation.ReceiverType);
        var returnType = operation.ReturnsVoid ? variant.Result.WrapVoid() : variant.Result.Wrap(operation.ReturnType);
        var parameters = BuildParameters(operation, variant, receiverType, receiverName);
        var guarded = GuardedNames(operation, variant, receiverName);

        WriteDocumentation(writer, operation, variant, guarded);

        // An async lambda converts to both Func<Task> and Func<ValueTask>; the overload with the most Task delegates wins.
        var taskDelegates = (variant.Delegate == Wrapper.Task ? 1 : 0) + (variant.Second == Wrapper.Task ? 1 : 0);

        if (taskDelegates > 0)
        {
            writer.Line($"[OverloadResolutionPriority({taskDelegates})]");
        }

        // The receiver is passed by value on purpose. Measured: `in` makes a chain slower, because the result of the previous call
        // is a temporary that has to be put in memory to take its address (see the ParameterPassing benchmark).
        writer.Line($"public static {returnType} {operation.Name}{operation.TypeParameterList}(this {string.Join(", ", WithDefaults(operation, parameters))})");

        EmitConstraints(writer, operation);
        writer.Open();

        if (stubs)
        {
            writer.Lines(StubBody(operation, variant));
        }
        else
        {
            EmitGuards(writer, guarded);
            EmitBody(writer, operation, variant, returnType, parameters);
        }

        writer.Close();
    }

    private static void EmitConstraints(CodeWriter writer, OperationSpec operation)
    {
        if (operation.NotNull.Length == 0 && operation.Structs.Length == 0 && operation.Constraints.Length == 0)
        {
            return;
        }

        writer.Indent();
        writer.Lines(operation.NotNull.Select(name => $"where {name} : notnull"));
        writer.Lines(operation.Structs.Select(name => $"where {name} : struct"));
        writer.Lines(operation.Constraints);
        writer.Unindent();
    }

    // The parameters of the signature: the plain list, with the default value of the parameters that have one.
    private static IEnumerable<string> WithDefaults(OperationSpec operation, List<string> parameters) => parameters.Select(parameter =>
    {
        var name = parameter[(parameter.LastIndexOf(' ') + 1)..];
        var extra = operation.ExtraParameters.FirstOrDefault(candidate => candidate.Name == name && candidate.DefaultValue is not null);

        return extra is null ? parameter : $"{parameter} = {extra.DefaultValue}";
    });

    private static void EmitGuards(CodeWriter writer, List<string> guarded)
    {
        writer.Lines(guarded.Select(name => $"Guard.NotNull({name}, nameof({name}));"));

        if (guarded.Count > 0)
        {
            writer.Line();
        }
    }

    private void EmitBody(CodeWriter writer, OperationSpec operation, Variant variant, string returnType, List<string> parameters)
    {
        var context = new BodyContext(variant, operation.ReturnType, profile);

        if (operation.ForwardsTo is { } target)
        {
            writer.Lines(ForwardingBody(operation, variant, target));
        }
        else if (variant.IsSync)
        {
            writer.Lines(operation.Body(context));
        }
        else if (variant.Receiver == Wrapper.None && operation.ForwardBody is not null)
        {
            writer.Lines(operation.ForwardBody(context));
        }
        else
        {
            if (variant.Receiver != Wrapper.None && !operation.SkipsCompletedFastPath)
            {
                EmitCompletedFastPath(writer, operation, variant, parameters, profile.ReceiverParameter);
            }

            EmitAsyncBody(writer, operation, variant, returnType, parameters);
        }
    }

    // A false condition returns the receiver as it was (the task it received, for a task receiver); a true one is the plain operation.
    private string[] ForwardingBody(OperationSpec operation, Variant variant, string target)
    {
        var receiver = profile.ReceiverParameter;
        var unchanged = (variant.Receiver, variant.Delegate) switch
        {
            (Wrapper.None, Wrapper.Task) => $"Task.FromResult({receiver})",
            (Wrapper.None, Wrapper.ValueTask) => $"new ValueTask<{operation.ReturnType}>({receiver})",
            _ => receiver,
        };
        var arguments = operation.Delegates.Select(@delegate => @delegate.Name).Concat(operation.ExtraParameters.Select(extra => extra.Name));

        return
        [
            $"if (!{operation.LeadingParameters[0].Name})",
            "{",
            $"    return {unchanged};",
            "}",
            string.Empty,
            $"return {target}({string.Join(", ", arguments.Prepend(receiver))});",
        ];
    }

    // When the receiver has already completed successfully there is nothing to wait for: run the synchronous variant (or the
    // one for the kind of the delegate) on its result and skip the state machine. Only a receiver that is still running,
    // faulted or cancelled takes the slow path, which awaits it and lets the exception travel.
    private void EmitCompletedFastPath(CodeWriter writer, OperationSpec operation, Variant variant, List<string> parameters, string receiverName)
    {
        var completed = variant.Receiver == Wrapper.Task ? $"{receiverName}.Status == TaskStatus.RanToCompletion" : $"{receiverName}.IsCompletedSuccessfully";
        var others = parameters.Skip(1).Select(parameter => parameter[(parameter.LastIndexOf(' ') + 1)..]);
        var call = $"{operation.Name}({receiverName}.Result{string.Concat(others.Select(name => ", " + name))})";

        writer.Line($"if ({completed})");
        writer.Open();

        if (variant.HasAsyncDelegate)
        {
            writer.Line($"var inner = {call};");
            writer.Line($"return {ConvertInner(operation, variant)};");
        }
        else
        {
            EmitSynchronousFastPath(writer, operation, variant, call, receiverName);
        }

        writer.Close();
        writer.Line();
    }

    // The fast path for a synchronous delegate: the result of the synchronous variant is wrapped in the kind of the receiver.
    private void EmitSynchronousFastPath(CodeWriter writer, OperationSpec operation, Variant variant, string call, string receiverName)
    {
        if (operation.ReturnsVoid)
        {
            writer.Line($"{call};");
            writer.Line(variant.Receiver == Wrapper.Task ? "return Task.CompletedTask;" : "return default;");
        }
        else if (variant.Receiver == Wrapper.Task && operation.KeepsValue && operation.StateChange == StateChange.Never)
        {
            writer.Line($"_ = {call};");
            writer.Line($"return {receiverName};");
        }
        else
        {
            writer.Line($"var completed = {call};");
            writer.Line(CompletedReturn(operation, variant, receiverName));
        }
    }

    private string CompletedReturn(OperationSpec operation, Variant variant, string receiverName)
    {
        if (variant.Receiver != Wrapper.Task)
        {
            return $"return new ValueTask<{operation.ReturnType}>(completed);";
        }

        return operation.KeepsValue
            ? $"return completed.HasSameStateAs({receiverName}.Result) ? {receiverName} : {ChangedTask(operation)};"
            : $"return {CompletedTask(operation)};";
    }

    // A task that ends in none hands out the cached completed task instead of allocating a new one.
    // The task for a state that differs from the receiver: only the outcomes that the operation can produce are generated.
    private string ChangedTask(OperationSpec operation) => operation.StateChange switch
    {
        StateChange.ToNone => NoneTask(operation),
        StateChange.FromNone or StateChange.ToFailure => "Task.FromResult(completed)",
        _ => CompletedTask(operation),
    };

    private string NoneTask(OperationSpec operation) =>
        profile.CachesCompletedNone ? $"MaybeTasks<{operation.ReturnType["Maybe<".Length..^1]}>.None" : "Task.FromResult(completed)";

    private string CompletedTask(OperationSpec operation)
    {
        if (profile.CachesCompletedNone && operation.ReturnType.StartsWith("Maybe<", StringComparison.Ordinal))
        {
            return $"completed.IsNone ? MaybeTasks<{operation.ReturnType["Maybe<".Length..^1]}>.None : Task.FromResult(completed)";
        }

        // Only a result without a value can share its task: a result with a value is a different task for every value.
        return profile.CachesCompletedSuccess && operation.ReturnType == "Result"
            ? "completed.IsSuccess ? ResultTasks.Success : Task.FromResult(completed)"
            : "Task.FromResult(completed)";
    }

    private void EmitAsyncBody(CodeWriter writer, OperationSpec operation, Variant variant, string returnType, List<string> parameters)
    {
        var argumentNames = parameters.Select(parameter => parameter[(parameter.LastIndexOf(' ') + 1)..]);

        writer.Line($"return Core({string.Join(", ", argumentNames)});");
        writer.Line();
        writer.Line($"static async {returnType} Core({string.Join(", ", parameters)})");
        writer.Open();

        if (variant.Receiver != Wrapper.None)
        {
            writer.Line($"var outcome = await {profile.ReceiverParameter}.ConfigureAwait({profile.ConfigurationClass}.ContinueOnCapturedContext);");
            writer.Line();
        }

        writer.Lines(operation.Body(new BodyContext(variant, operation.ReturnType, profile)));
        writer.Close();
    }

    private void WriteDocumentation(CodeWriter writer, OperationSpec operation, Variant variant, List<string> guarded)
    {
        writer.Line($"/// <summary>{operation.Summary}{VariantSentence(operation, variant)}</summary>");

        foreach (var typeParameter in operation.TypeParameterDocs)
        {
            writer.Line($"/// <typeparam name=\"{typeParameter.Name}\">{typeParameter.Description}</typeparam>");
        }

        writer.Line($"/// <param name=\"{profile.ReceiverParameter}\">{ReceiverDescription(variant.Receiver)}</param>");

        foreach (var leading in operation.LeadingParameters)
        {
            writer.Line($"/// <param name=\"{leading.Name}\">{leading.Description}</param>");
        }

        foreach (var @delegate in operation.Delegates)
        {
            writer.Line($"/// <param name=\"{@delegate.Name}\">{@delegate.Description}</param>");
        }

        foreach (var extra in operation.ExtraParameters)
        {
            writer.Line($"/// <param name=\"{extra.Name}\">{extra.Description}</param>");
        }

        writer.Line($"/// <returns>{operation.ReturnDescription}{ReturnSentence(operation, variant)}</returns>");

        if (guarded.Count > 0)
        {
            var references = string.Join(", ", guarded.Select(name => $"<paramref name=\"{name}\"/>"));
            writer.Line($"/// <exception cref=\"ArgumentNullException\">{references} is <see langword=\"null\"/>.</exception>");
        }
    }

    private string AwaitedWithoutContext() =>
        $"awaited without capturing the synchronization context unless <see cref=\"{profile.OptionsClass}.ContinueOnCapturedContext\"/> says otherwise.";

    private string VariantSentence(OperationSpec operation, Variant variant)
    {
        var sentence = string.Empty;

        if (variant.Receiver != Wrapper.None)
        {
            sentence += $" The receiver is a {variant.Receiver.Label()} that produces the {profile.ReceiverParameter}; it is " + AwaitedWithoutContext();
        }

        // With two kinds of delegate each sentence names its parameter; with one, "the delegate" is enough.
        var first = operation.HasIndependentDelegate ? $"<paramref name=\"{operation.Delegates.First(spec => !spec.Independent).Name}\"/>" : "delegate";
        var second = operation.HasIndependentDelegate ? $"<paramref name=\"{operation.Delegates.First(spec => spec.Independent).Name}\"/>" : "delegate";

        if (variant.Delegate != Wrapper.None)
        {
            sentence += $" The {first} is asynchronous (it returns a {variant.Delegate.Label()}) and is " + AwaitedWithoutContext();
        }

        if (variant.Second != Wrapper.None)
        {
            sentence += $" The {second} is asynchronous (it returns a {variant.Second.Label()}) and is " + AwaitedWithoutContext();
        }

        return sentence;
    }

    private string ReceiverDescription(Wrapper receiver) => receiver switch
    {
        Wrapper.None => $"The {profile.ReceiverParameter} to operate on.",
        Wrapper.Task => $"The task that produces the {profile.ReceiverParameter} to operate on. It must not be <see langword=\"null\"/>.",
        _ => $"The value task that produces the {profile.ReceiverParameter} to operate on.",
    };
}
