namespace Wyzely.Functional.CodeGeneration;

/// <summary>Writes one test class per operation family: every test case, in every one of the nine variants.</summary>
internal sealed class TestEmitter(GeneratorProfile profile)
{
    internal string Emit(OperationSpec operation)
    {
        var writer = new CodeWriter();
        writer.Line("// <auto-generated>");
        writer.Line($"//     This file was generated by {profile.ToolNamespace}. Do not edit it by hand:");
        writer.Line($"//     change the generator and run `dotnet run --project {profile.ToolProject}`.");
        writer.Line("// </auto-generated>");
        writer.Line("#nullable enable");
        writer.Line();
        writer.Line($"namespace {profile.TestNamespace};");
        writer.Line();
        writer.Line($"public sealed class {operation.Stem}MatrixTests");
        writer.Open();

        var first = true;

        foreach (var testCase in operation.Tests)
        {
            foreach (var variant in operation.Variants)
            {
                if (!first)
                {
                    writer.Line();
                }

                first = false;
                EmitTest(writer, operation, testCase, variant, pending: false);

                if (variant.Receiver != Wrapper.None)
                {
                    writer.Line();
                    EmitTest(writer, operation, testCase, variant, pending: true);
                }
            }
        }

        writer.Close();

        return writer.ToString();
    }

    private void EmitTest(CodeWriter writer, OperationSpec operation, TestCaseSpec testCase, Variant variant, bool pending)
    {
        var name = TestName(operation, testCase, variant, pending);
        var isAsync = !variant.IsSync;
        var delegates = operation.Delegates
            .Select(spec => (Spec: spec, Test: testCase.Delegates.Single(test => test.DelegateName == spec.Name)))
            .ToList();

        writer.Line("[Fact]");
        writer.Line(isAsync ? $"internal async Task {name}()" : $"internal void {name}()");
        writer.Open();
        writer.Lines(profile.TestPreamble);

        if (testCase.Setup is not null)
        {
            writer.Lines(testCase.Setup);
        }

        foreach (var (_, test) in delegates)
        {
            writer.Line($"var {test.DelegateName}Calls = 0;");
        }

        // A receiver that completes later is a task that the test completes itself, after the call has returned: the call has then awaited it,
        // so the path of a pending receiver is the one that runs. (A task that completes on its own after a yield may be done before the call
        // looks at it, depending on how fast the thread that runs the call is; that made the coverage of this path vary from run to run.)
        // A test that records an exception wraps the call in a lambda, and keeps the yield.
        var gated = pending && !testCase.RecordsException;

        writer.Lines(ReceiverLines(testCase.Receiver, operation.ReceiverTestType, variant.Receiver, pending, gated));

        var arguments = (testCase.LeadingArguments ?? [])
            .Concat(delegates.Select(pair => RenderLambda(pair.Test, variant.WrapperOf(pair.Spec))))
            .Concat(testCase.ExtraArguments);
        var call = $"receiver.{operation.Name}({string.Join(", ", arguments)})";

        writer.Lines(gated
            ? GatedCall(operation, testCase.Receiver, call)
            : [CallStatement(operation, testCase, call, isAsync)]);
        writer.Line();
        writer.Lines(testCase.Asserts);
        writer.Close();
    }

    // The lines that create the receiver; for a gated one, the source that the test completes later.
    private static string[] ReceiverLines(string expression, string receiverType, Wrapper receiver, bool pending, bool gated)
    {
        if (!gated)
        {
            return [$"var receiver = {WrapReceiver(expression, receiverType, receiver, pending)};"];
        }

        var task = receiver == Wrapper.Task ? "source.Task" : $"new ValueTask<{receiverType}>(source.Task)";

        return [$"var source = new TaskCompletionSource<{receiverType}>();", $"var receiver = {task};"];
    }

    // Starts the call without awaiting it, checks that it is still pending, completes the receiver and then awaits the call.
    private static string[] GatedCall(OperationSpec operation, string receiverValue, string call) =>
    [
        $"var call = {call};",
        "Assert.False(call.IsCompleted);",
        $"source.SetResult({receiverValue});",
        operation.ReturnsVoid ? "await call;" : "var outcome = await call;",
    ];

    private static string TestName(OperationSpec operation, TestCaseSpec testCase, Variant variant, bool pending)
    {
        var suffix = pending ? "_when_the_receiver_completes_later" : string.Empty;
        var delegatePart = operation.Delegates.Length == 0 ? string.Empty : $"with_{variant.Delegate.Slug()}_delegate_";
        var secondPart = operation.HasIndependentDelegate ? $"and_{variant.Second.Slug()}_second_delegate_" : string.Empty;

        return $"{operation.Name}_on_{variant.Receiver.Slug()}_receiver_{delegatePart}{secondPart}{testCase.Name}{suffix}";
    }

    // The statement that makes the call: recorded when an exception is expected, discarded for a void operation, otherwise kept in `outcome`.
    private static string CallStatement(OperationSpec operation, TestCaseSpec testCase, string call, bool isAsync)
    {
        if (testCase.RecordsException)
        {
            return RecordException(operation, call, isAsync);
        }

        var awaitPrefix = isAsync ? "await " : string.Empty;

        return operation.ReturnsVoid ? $"{awaitPrefix}{call};" : $"var outcome = {awaitPrefix}{call};";
    }

    // The call of an operation that is expected to throw, with the exception kept in `exception` (null when nothing was thrown).
    private static string RecordException(OperationSpec operation, string call, bool isAsync)
    {
        if (isAsync)
        {
            return operation.ReturnsVoid
                ? $"var exception = await Record.ExceptionAsync(async () => await {call});"
                : $"var exception = await Record.ExceptionAsync(async () => {{ _ = await {call}; }});";
        }

        return operation.ReturnsVoid
            ? $"var exception = Record.Exception(() => {call});"
            : $"var exception = Record.Exception(() => {{ _ = {call}; }});";
    }

    private static string WrapReceiver(string expression, string receiverType, Wrapper receiver, bool pending)
    {
        var task = pending ? $"Pending.Of({expression})" : $"Task.FromResult({expression})";

        return receiver switch
        {
            Wrapper.None => expression,
            Wrapper.Task => task,
            _ => pending ? $"new ValueTask<{receiverType}>({task})" : $"new ValueTask<{receiverType}>({expression})",
        };
    }

    private static string RenderLambda(DelegateTest test, Wrapper wrapper)
    {
        var parameters = test.Parameters.Length == 1 ? test.Parameters[0] : "(" + string.Join(", ", test.Parameters) + ")";
        var body = $"{test.DelegateName}Calls++; ";

        if (test.Statements.Length > 0)
        {
            body += test.Statements + " ";
        }

        if (wrapper == Wrapper.Task)
        {
            // A real async lambda: the form users write, and the one that must not be ambiguous between Task and ValueTask.
            body += "await Task.Yield(); ";
        }

        if (test.Return is null)
        {
            body += wrapper == Wrapper.ValueTask ? "return ValueTask.CompletedTask; " : string.Empty;
        }
        else
        {
            body += wrapper == Wrapper.ValueTask
                ? $"return new ValueTask<{test.ReturnType}>({test.Return}); "
                : $"return {test.Return}; ";
        }

        var modifier = wrapper == Wrapper.Task ? "async " : string.Empty;

        return $"{modifier}{parameters} => {{ {body}}}";
    }
}
